export function mapServiceLibraryToCatalogEntry(entry) {
  if (!entry) return null;
  return {
    id: entry.id,
    name: entry.name,
    price: entry.price,
    image: entry.image,
  };
}

export function serviceLibraryCatalogEntry(id) {
  const row = S2_SERVICE_LIBRARY.find((s) => s.id === id);
  return mapServiceLibraryToCatalogEntry(row);
}
